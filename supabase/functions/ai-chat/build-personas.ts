// Regenerates personas.generated.ts from personas/*.md. Run from the repo root:
//   deno run --allow-read --allow-write supabase/functions/ai-chat/build-personas.ts
import { extractPrompt } from './persona_lib.ts';

const dir = new URL('./personas/', import.meta.url);
const out: Record<string, string> = {};
for (const tag of ['hexa', 'cyphr']) {
  out[tag] = extractPrompt(await Deno.readTextFile(new URL(`${tag}.md`, dir)));
}
const ts = `// GENERATED by build-personas.ts from personas/*.md. Do not edit by hand.\n` +
  `export const PERSONAS: Record<'hexa' | 'cyphr', string> = ${JSON.stringify(out, null, 2)};\n`;
await Deno.writeTextFile(new URL('./personas.generated.ts', import.meta.url), ts);
console.log('personas.generated.ts written');
